print(classroom)


# 5번. 중첩 리스트에서 특정 학생 이름 출력하기
## 문제 4에서 만든 classroom 리스트를 이용하여, 2반의 두 번째 학생인 '서연'의 이름을 인덱싱으로 추출하여 출력하는 코드를 작성하세요
