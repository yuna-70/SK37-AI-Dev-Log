# 2번. f-string을 이용한 자기소개
## 이름과 나이를 각각 name과 age 변수에 저장한 후, f-string을 사용하여 "제 이름은 OOO이고, 나이는 OO세입니다." 형식으로 문장을 출력하는 코드를 작성하세요.

name = "강유나"
age = 28
print(f'제 이름은 {name}이고, 나이는 {age}세입니다.')


# 3번. 인덱싱으로 요일 선택하기
## 일주일의 요일이 담긴 week 리스트가 있습니다. 인덱싱을 사용하여 '수요일'을 today 변수에 저장하고, today 변수를 출력하는 코드를 작성하세요.

week = ['월요일', '화요일', '수요일', '목요일', '금요일', '토요일', '일요일']
today = week[2]
print(today)


# 4번. 중첩 리스트 생성 및 출력
## 2개의 반 학생들 이름으로 구성된 중첩 리스트 classroom을 만드세요.
## ● 1반: '철수', '영희'
## ● 2반: '민준', '서연'
## 그리고 classroom 리스트 전체를 출력하는 코드를 작성하세요.

